"""Generates app/lib/data/db/schema.drift from docs/schema/local.sql (the canonical schema).
Drift needs no PRAGMA line, and a friendlier Dart class name for the quoted "order" table.
Run: python3 -I tool/sync_schema.py"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
sql = (root / "docs/schema/local.sql").read_text()
sql = re.sub(r"^PRAGMA .*\n", "", sql, flags=re.M)
sql = sql.replace('''  version INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX order_date_ix''', '''  version INTEGER NOT NULL DEFAULT 1
) AS OrderRow;
CREATE INDEX order_date_ix''')
out = root / "app/lib/data/db/schema.drift"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("-- GENERATED by tool/sync_schema.py from docs/schema/local.sql. Do not edit.\n" + sql)
print("wrote", out)
